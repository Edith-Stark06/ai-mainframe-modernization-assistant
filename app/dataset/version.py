"""
Phase 6 versioning constants (#118 / #119 / #120).

Every artifact Phase 6 produces records the exact versions that produced
it, so a later "is the AI improving?" comparison is unambiguous:

* ``DATASET_VERSION``   — the training-dataset build (#118). ``phase6-v1``
  is the original build; its training corpus overlapped the #119
  benchmark, so #121's leakage guard rejects it.
* ``DATASET_VERSION_V2`` — ``phase6-v2``: a rebuild whose training corpus
  is **source-disjoint from the benchmark** (see
  :func:`app.dataset.corpus.load_training_corpus`). This is what a real
  #121 fine-tuning run consumes. ``phase6-v1`` stays untouched and
  reproducible.
* ``BENCHMARK_VERSION`` — the frozen evaluation benchmark (#119). This is
  a **separate** namespace from the dataset on purpose — the benchmark is
  never regenerated by the dataset builder and never used as training
  data. Unchanged by the v2 rebuild.
* ``PROMPT_VERSION``    — the prompt templates used by #120.
* ``GENERATOR_VERSION`` — the dataset/benchmark *builder* code version;
  bumped whenever the generation logic changes even if the schema does
  not.
* ``ANALYSIS_VERSION``  — the deterministic Phase 1–5 analysis contract
  the examples' ``analysis`` blocks were produced against.

Bump a version by editing this file; never silently overwrite a
historical dataset or benchmark directory.
"""

